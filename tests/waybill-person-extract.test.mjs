import fs from "node:fs";
import assert from "node:assert/strict";
const source=fs.readFileSync(new URL("../functions/api/waybills/process.js",import.meta.url),"utf8");
const start=source.indexOf("function extract(rawText)");
const end=source.indexOf("\nfunction baseIdentityNames",start);
assert.ok(start>=0&&end>start,"waybill extract function must exist");
const clean=value=>String(value??"").trim();
const number=value=>{const n=Number(value);return Number.isFinite(n)?n:null};
const extract=new Function("clean","number",source.slice(start,end)+"\nreturn extract;")(clean,number);
const multiline=extract("运输日期：2026-10-16\n主司机：张三\n送货员：李四\n车牌号：渝 DK 7692\n重庆门店甲");
assert.equal(multiline.driver,"张三","司机姓名应支持标签和值同一行");
assert.equal(multiline.deliveryPerson,"李四","送货员姓名应支持标签和值同一行");
assert.equal(multiline.vehicle,"渝DK7692","司机/送货员提取不应影响车牌，且应兼容 OCR 将车牌拆开");
const sameLine=extract("主司机 王师傅 送货员 赵师傅 车辆 渝DK7692");
assert.equal(sameLine.driver,"王师傅","同一行多个字段时应提取司机");
assert.equal(sameLine.deliveryPerson,"赵师傅","同一行多个字段时应提取送货员");
const splitLabel=extract("主司机\n王师傅\n送货员\n赵师傅");
assert.equal(splitLabel.driver,"王师傅","标签和值分行时应提取司机");
assert.equal(splitLabel.deliveryPerson,"赵师傅","标签和值分行时应提取送货员");
const missing=extract("车辆：渝DK7692\n重庆门店甲");
assert.equal(missing.driver,null,"没有司机字段时应保持为空");
assert.equal(missing.deliveryPerson,null,"没有送货员字段时应保持为空");
console.log("waybill driver/delivery extraction regression passed");
